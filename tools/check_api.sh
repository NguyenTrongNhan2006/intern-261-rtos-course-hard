#!/usr/bin/env bash
# Kiem tra bai nop - BAN KHO. Usage: ./tools/check_api.sh [path ...]   (exit 0 = sach)
#  1. Chi API goc FreeRTOS (khong cmsis_os / os*)
#  2. Khong HAL / LL - chi thao tac thanh ghi qua stm32f1xx.h
#  3. Khong file do cong cu sinh ra (CubeMX .ioc, 'USER CODE BEGIN', Makefile)
#  4. Tu week1/ex4 tro di: chi cap phat tinh (*Static)
# Comment duoc loc truoc khi do API, nen cau "khong dung HAL" trong comment khong bi bat nham.
set -uo pipefail

TARGETS=("$@")
[ ${#TARGETS[@]} -eq 0 ] && TARGETS=(platform week1 week2 week3 week4)
EXISTING=()
for t in "${TARGETS[@]}"; do [ -e "$t" ] && EXISTING+=("$t"); done
if [ ${#EXISTING[@]} -eq 0 ]; then echo "check_api: nothing to check"; exit 0; fi

mapfile -d '' SRC < <(find "${EXISTING[@]}" -type f -not -path '*/build/*' \
  \( -name '*.c' -o -name '*.h' -o -name '*.s' -o -name '*.S' -o -name '*.ld' \
     -o -name 'CMakeLists.txt' -o -name '*.cmake' -o -name 'CMakePresets.json' \) -print0)

strip_comments() {
  python3 - "$1" <<'PY'
import re, sys
src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
src = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)
if sys.argv[1].endswith(("CMakeLists.txt", ".cmake")):
    src = re.sub(r"#[^\n]*", "", src)
sys.stdout.write(src)
PY
}

fail=0
report() { echo "  $1"; fail=1; }

CMSIS_OS='cmsis_os|\bos(Kernel|Thread|Delay|MessageQueue|Mutex|Semaphore|EventFlags|Timer|Memory)[A-Za-z]*[[:space:]]*\('
HAL_LL='\b(HAL|LL)_[A-Za-z]|stm32f1xx_(hal|ll)'
DYN='\b(pvPortMalloc|xTaskCreate|xQueueCreate|xSemaphoreCreate(Mutex|Binary|Counting|RecursiveMutex)|xEventGroupCreate|xTimerCreate|xStreamBufferCreate|xMessageBufferCreate)[[:space:]]*\('

for f in "${SRC[@]}"; do
  code=$(strip_comments "$f")
  h=$(grep -nE "$CMSIS_OS" <<<"$code") && { echo "$f"; while read -r l; do report "CMSIS-OS   $l"; done <<<"$h"; }
  h=$(grep -nE "$HAL_LL"   <<<"$code") && { echo "$f"; while read -r l; do report "HAL/LL     $l"; done <<<"$h"; }
  h=$(grep -nE 'USER CODE (BEGIN|END)|Auto-generated by|STM32CubeMX' "$f") && { echo "$f"; while read -r l; do report "GENERATED  $l"; done <<<"$h"; }
  case "$f" in
    week1/ex4/*|*/week1/ex4/*|week[234]*|*/week[234]*)
      h=$(grep -nE "$DYN" <<<"$code") && { echo "$f"; while read -r l; do report "DYNAMIC    $l"; done <<<"$h"; } ;;
  esac
done

if g=$(find "${EXISTING[@]}" \( -name '*.ioc' -o -name Makefile -o -name '*.mk' \) -not -path '*/build/*' | grep .); then
  while read -r l; do report "FORBIDDEN FILE  $l"; done <<<"$g"
fi

if [ $fail -ne 0 ]; then
  echo
  echo "check_api: FAIL — xem cac dong tren. Phan code cua bai vi pham = 0 diem."
  exit 1
fi
echo "check_api: PASS (${#SRC[@]} files)"
